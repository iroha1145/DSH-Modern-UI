#!/usr/bin/env node
// Writes the openui-lang part of the model prompt from the component library and the DSH prompt
// options, after checking that every worked example parses against that library. The Host entry
// imports the generated string, so it never loads React components. `--check` fails instead of
// writing when the committed file is stale.
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { build } from 'esbuild'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const source = path.join(root, 'packages/modern-ui/src/vendor/openui')
const target = path.join(source, 'system-prompt.generated.ts')
const check = process.argv.includes('--check')

const scratch = await mkdtemp(path.join(tmpdir(), 'openui-prompt-'))
try {
  const bundle = path.join(scratch, 'prompt-source.mjs')
  await build({
    absWorkingDir: root,
    stdin: {
      contents: [
        `export { library } from ${JSON.stringify(path.join(source, 'library.ts'))}`,
        `export { promptOptions, examples } from ${JSON.stringify(path.join(source, 'prompt-options.ts'))}`,
        `export { createParser } from '@openuidev/lang-core'`,
      ].join('\n'),
      resolveDir: root,
      loader: 'ts',
    },
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node24',
    jsx: 'automatic',
    outfile: bundle,
    logLevel: 'silent',
    define: { 'process.env.NODE_ENV': '"production"' },
    plugins: [
      {
        name: 'no-styles',
        setup(builder) {
          builder.onResolve({ filter: /\.css$/ }, args => ({ path: args.path, namespace: 'no-styles' }))
          builder.onLoad({ filter: /.*/, namespace: 'no-styles' }, () => ({ contents: '', loader: 'js' }))
        },
      },
    ],
  })
  const { library, promptOptions, examples, createParser } = await import(pathToFileURL(bundle).href)

  const parser = createParser(library.toJSONSchema(), library.root)
  const problems = []
  for (const [name, code] of Object.entries(examples)) {
    const result = parser.parse(code)
    const issues = [
      ...(result.root === null ? ['no root'] : []),
      ...result.meta.errors.map(error => error.message),
      ...result.meta.unresolved.map(name => `unresolved ${name}`),
      ...result.meta.orphaned.map(name => `orphaned ${name}`),
    ]
    if (issues.length > 0) problems.push(`${name}: ${issues.join('; ')}`)
  }
  if (problems.length > 0) {
    console.error(`Prompt examples do not parse against the library:\n${problems.join('\n')}`)
    process.exitCode = 1
  } else {
    const prompt = library.prompt(promptOptions)
    const text = `// Generated by scripts/generate-openui-prompt.mjs from library.ts and prompt-options.ts; do not edit.\n/** The openui-lang part of the response-presentation prompt. */\nexport const OPENUI_SYSTEM_PROMPT = ${JSON.stringify(prompt)}\n`
    const current = await readFile(target, 'utf8').catch(() => '')
    if (check) {
      if (current !== text) {
        console.error(`${path.relative(root, target)} is stale; run npm run prompt:openui`)
        process.exitCode = 1
      }
    } else if (current !== text) {
      await writeFile(target, text)
      console.log(`Wrote ${path.relative(root, target)} (${prompt.length} characters)`)
    } else {
      console.log(`${path.relative(root, target)} is up to date (${prompt.length} characters)`)
    }
  }
} finally {
  await rm(scratch, { recursive: true, force: true })
}
